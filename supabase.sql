create table if not exists public.site_settings (
  id integer primary key default 1 check (id = 1),
  business_name text not null default 'Tech Zone',
  tagline text not null default 'Tecnología en buenas manos',
  phone text not null default '',
  whatsapp text not null default '',
  instagram text not null default '',
  address text not null default 'San Justo, Santa Fe',
  hours text not null default 'Consultar horarios',
  about text not null default 'Reparamos tus equipos con atención personalizada.',
  updated_at timestamptz not null default now()
);

insert into public.site_settings (id) values (1) on conflict (id) do nothing;

create table if not exists public.site_services (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  icon text not null default 'cpu',
  visible boolean not null default true,
  created_at timestamptz not null default now()
);

insert into public.site_services (title, description, icon) values
