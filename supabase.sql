('Cambio de módulo', 'Reemplazo de pantalla y módulo para celulares. Consultá disponibilidad según tu modelo.', 'phone'),
('Baterías y carga', 'Cambio de batería, revisión de pin de carga y diagnóstico de problemas de alimentación.', 'battery'),
('Reparación de hardware', 'Diagnóstico de componentes, almacenamiento, memoria, conectores y otras fallas.', 'cpu')
on conflict do nothing;

create table if not exists public.site_photos (
  id bigint generated by default as identity primary key,
  title text not null default 'Trabajo realizado',
  description text not null default '',
  image_url text not null,
  storage_path text not null,
  created_at timestamptz not null default now()
);

alter table public.site_settings enable row level security;
alter table public.site_services enable row level security;
alter table public.site_photos enable row level security;

drop policy if exists "Public can read settings" on public.site_settings;
create policy "Public can read settings" on public.site_settings for select using (true);
drop policy if exists "Authenticated can edit settings" on public.site_settings;
create policy "Authenticated can edit settings" on public.site_settings for all to authenticated using (true) with check (true);

drop policy if exists "Public can read visible services" on public.site_services;
create policy "Public can read visible services" on public.site_services for select using (visible = true or auth.role() = 'authenticated');
drop policy if exists "Authenticated can manage services" on public.site_services;
create policy "Authenticated can manage services" on public.site_services for all to authenticated using (true) with check (true);

drop policy if exists "Public can read photos" on public.site_photos;
create policy "Public can read photos" on public.site_photos for select using (true);
drop policy if exists "Authenticated can manage photos" on public.site_photos;
create policy "Authenticated can manage photos" on public.site_photos for all to authenticated using (true) with check (true);

-- Storage: creá un bucket público llamado tech-zone-photos en Storage.
-- Estas políticas permiten que usuarios autenticados suban y eliminen fotos.
drop policy if exists "Authenticated can upload Tech Zone photos" on storage.objects;
create policy "Authenticated can upload Tech Zone photos" on storage.objects for insert to authenticated with check (bucket_id = 'tech-zone-photos');
drop policy if exists "Authenticated can update Tech Zone photos" on storage.objects;
create policy "Authenticated can update Tech Zone photos" on storage.objects for update to authenticated using (bucket_id = 'tech-zone-photos') with check (bucket_id = 'tech-zone-photos');
drop policy if exists "Authenticated can delete Tech Zone photos" on storage.objects;
create policy "Authenticated can delete Tech Zone photos" on storage.objects for delete to authenticated using (bucket_id = 'tech-zone-photos');
